// Marker radius scales by sqrt(visits) (same reasoning as
// HeatmapPanel.tsx's cellOpacity: linear scaling lets one dominant
// country swamp every other marker down to near-invisible), clamped to
// a sane range so a single-visit country is still visible and a
// huge one doesn't swallow its neighbors.
function markerRadius(visits: number, max: number): number {
  if (max <= 0 || visits <= 0) return 0;
  return Math.max(4, Math.min(22, Math.sqrt(visits / max) * 22));
}

interface WorldMapProps {
  countries: CountryRow[];
}

export function WorldMap({ countries }: WorldMapProps) {
  const [hovered, setHovered] = useState<string | null>(null);

  const markers = useMemo(() => {
    const max = countries[0]?.visits || 1;
    return countries
      .map((c) => {
        const geo = countryLatLng(c.code);
        if (!geo) return null;
        const [x, y] = project(geo[0], geo[1]);
        return { ...c, x, y, r: markerRadius(c.visits, max) };
      })
      .filter((m): m is NonNullable<typeof m> => m !== null)
      // Smallest-first so a big hotspot's halo never visually buries a
      // smaller nearby country's own marker underneath it.
      .sort((a, b) => a.r - b.r);
  }, [countries]);

  const active = markers.find((m) => m.code === hovered) || null;
  // countries is already visits-desc (see aggregateVisits in
  // lib/dashboardStats.ts), so [0] is simply the top country — no need
  // to infer it from the radius-sorted markers array above.
  const topCode = countries[0]?.code;
  const mapLabel = topCode ? `Visitor map — top country ${getCountryName(topCode)}` : 'Visitor map';

  if (markers.length === 0) {
    return (
      <div className="dx-wmap dx-wmap-empty">
        <svg viewBox={`0 0 ${MAP_W} ${MAP_H}`} role="img" aria-label="World map, no visitor data yet">
          {DOT_MAP.map(([x, y], i) => (
            <circle key={i} cx={x} cy={y} r={2.1} className="dx-wmap-land" />
          ))}
        </svg>
        <p className="dx-empty">Visitor locations will appear here as people arrive.</p>
      </div>
    );
  }

  return (
    <div className="dx-wmap">
      <svg viewBox={`0 0 ${MAP_W} ${MAP_H}`} role="img" aria-label={mapLabel}>
        {DOT_MAP.map(([x, y], i) => (
          <circle key={i} cx={x} cy={y} r={2.1} className="dx-wmap-land" />
        ))}
        {markers.map((m) => (
          <g
            key={m.code || 'unknown'}
            className={hovered === m.code ? 'dx-wmap-marker is-active' : 'dx-wmap-marker'}
            onPointerEnter={() => setHovered(m.code)}
            onPointerLeave={() => setHovered((h) => (h === m.code ? null : h))}
          >
            <circle cx={m.x} cy={m.y} r={m.r * 2} className="dx-wmap-halo" />
            <circle cx={m.x} cy={m.y} r={m.r} className="dx-wmap-dot" />
            <title>
              {m.code ? getCountryName(m.code) : 'Unknown'} — {fmtNum(m.visits)} visit{m.visits === 1 ? '' : 's'}
            </title>
          </g>
        ))}
      </svg>

      {active && (
        <div className="dx-wmap-tip" style={{ left: `${(active.x / MAP_W) * 100}%`, top: `${(active.y / MAP_H) * 100}%` }}>
          <span className="dx-wmap-tip-flag" aria-hidden="true">
            {countryCodeToFlag(active.code)}
          </span>
          <span className="dx-wmap-tip-main">
            <b>{active.code ? getCountryName(active.code) : 'Unknown'}</b>
            <small>
              {fmtNum(active.visits)} visit{active.visits === 1 ? '' : 's'} · {fmtNum(active.visitors)} unique
            </small>
          </span>
        </div>
      )}
    </div>
  );
}
