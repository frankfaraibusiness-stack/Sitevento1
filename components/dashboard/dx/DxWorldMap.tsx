// — ~1,070 points, hand-built, equirectangular, viewBox 0 0 1000 440,
// covering lon -170..180 / lat 75..-58). It's deliberately stylized
// rather than coastline-precise: there's no mapping/charting dependency
// anywhere in this project to render a real vector basemap from, and a
// precise one would mean shipping an external asset — this keeps the
// panel fully self-contained like everything else here. Markers are
// plotted on top from lib/countryGeo.ts's per-country centroid using
// the exact same projection math, so a country's dot always lands
// inside its own silhouette on the backdrop.
