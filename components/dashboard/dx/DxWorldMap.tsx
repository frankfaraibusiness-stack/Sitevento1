const MAP_W = 1000;
const MAP_H = 440;
const LON_MIN = -170;
const LON_MAX = 180;
const LAT_MAX = 75;
const LAT_MIN = -58;

function project(lat: number, lon: number): [number, number] {
  const x = ((lon - LON_MIN) / (LON_MAX - LON_MIN)) * MAP_W;
  const y = ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * MAP_H;
  return [x, y];
}

